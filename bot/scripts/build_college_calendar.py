"""Build web calendar files from the bot's confirmed rules.

Usage: python scripts/build_college_calendar.py /path/to/web
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from college_calendar import EXCEPTIONS


def build(web_root):
    web_root = Path(web_root)
    (web_root / 'static/js').mkdir(parents=True, exist_ok=True)
    (web_root / 'college_calendar.py').write_bytes((ROOT / 'college_calendar.py').read_bytes())
    rules = json.dumps(EXCEPTIONS, ensure_ascii=False, separators=(',', ':'))
    script = '''// Generated by bot/scripts/build_college_calendar.py. Edit college_calendar.py.
(function () {
    'use strict';
    const rules = RULES;
    Object.values(rules).forEach(Object.freeze);
    Object.freeze(rules);
    function key(value) {
        if (typeof value === 'string') return value;
        if (!(value instanceof Date) || !Number.isFinite(value.getTime())) return '';
        return [value.getFullYear(), String(value.getMonth() + 1).padStart(2, '0'),
            String(value.getDate()).padStart(2, '0')].join('-');
    }
    function isHoliday(value) { return rules[key(value)]?.kind === 'holiday'; }
    function isSaturday(value) {
        if (isHoliday(value)) return false;
        const day = value instanceof Date ? value : new Date(key(value) + 'T12:00:00');
        return day.getDay() === 6 || rules[key(value)]?.kind === 'saturday_hours';
    }
    window.kkepikCalendar = Object.freeze({ rules, isHoliday, isSaturday });
})();
'''.replace('RULES', rules)
    (web_root / 'static/js/college_calendar.js').write_text(script, encoding='utf-8')


if __name__ == '__main__':
    build(sys.argv[1])
